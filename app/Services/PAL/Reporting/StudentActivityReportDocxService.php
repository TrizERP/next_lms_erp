<?php

namespace App\Services\PAL\Reporting;

use PhpOffice\PhpWord\Element\Section;
use PhpOffice\PhpWord\IOFactory;
use PhpOffice\PhpWord\PhpWord;

/**
 * Renders a StudentActivityReportService report array as a .docx file.
 *
 * FIRST WRITE-USAGE OF PHPWORD IN THIS CODEBASE
 * Every existing use of phpoffice/phpword here (HomeworkDocumentExtractionService,
 * LmsAssignmentApiController) only READS an uploaded .docx. There is no
 * existing write pattern to copy, so this goes straight to the official
 * PhpWord API (Section::addText/addTable/addListItem, Writer\Word2007) rather
 * than guessing at an in-house convention that doesn't exist.
 *
 * SECTION-PER-METHOD, MIRRORING RendersContentPresentation
 * That trait builds a .pptx one slide-kind at a time (writeCoverSlide,
 * writeTilesSlide, writeContentSlide, ...); this does the same thing one
 * report section at a time, in the order the brief specifies: title block ->
 * mastery overview -> diagnostic & adaptive performance -> misconception
 * analysis -> gamification & engagement -> recommendations/action items. It
 * is written as a plain injectable service, not a trait, because exactly one
 * controller (StudentActivityReportController) ever calls it.
 *
 * NO CHART, BY DESIGN
 * There is no server-side charting library in this codebase (the same
 * constraint RendersContentPresentation documents for the slide deck). The
 * diagnostic trend is rendered as a plain date/percentage table with a
 * ▲ / ▼ / ▬ glyph column instead of a drawn line.
 *
 * Returns the finished file as a binary string (the tempnam -> save ->
 * file_get_contents -> unlink round-trip RendersContentPresentation also
 * uses for its .pptx), so the controller can hand it straight to
 * response()->streamDownload() without managing a temp file of its own.
 */
class StudentActivityReportDocxService
{
    public function __construct(private StudentActivityChartRenderer $charts)
    {
    }

    private const FONT = 'Calibri';

    private const INK = '1E293B';
    private const MUTED = '475569';
    private const BRAND_DARK = '3730A3';
    private const SURFACE = 'EEF2FF';
    private const LINE = 'C7D2FE';

    private const TABLE_STYLE = ['borderSize' => 6, 'borderColor' => self::LINE, 'cellMargin' => 80];
    private const HEADER_CELL = ['bgColor' => self::SURFACE];
    private const HEADER_FONT = ['bold' => true, 'size' => 9, 'color' => self::BRAND_DARK];
    private const BODY_FONT = ['size' => 9];
    private const HEADING_FONT = ['bold' => true, 'size' => 14, 'color' => self::BRAND_DARK];
    private const HEADING_PARA = ['spaceBefore' => 200, 'spaceAfter' => 120];

    /** Friendly labels for whichever scope keys a report actually carries. */
    private const SCOPE_LABELS = [
        'learner_id' => 'Learner ID',
        'learner_name' => 'Learner',
        'standard_id' => 'Standard ID',
        'section_id' => 'Section ID',
        'subject_id' => 'Subject ID',
        'syear' => 'Academic year',
        'student_count' => 'Students in scope',
        'from' => 'From',
        'to' => 'To',
    ];

    public function generateStudentReport(array $reportData): string
    {
        return $this->render($reportData, 'PAL Student Activity & Performance Report', 'recommendations', 'Recommendations');
    }

    public function generateClassReport(array $reportData): string
    {
        return $this->render($reportData, 'PAL Class Activity & Performance Report', 'action_items', 'Action Items');
    }

    /** @return string Binary .docx */
    private function render(array $reportData, string $title, string $bulletsKey, string $bulletsHeading): string
    {
        // PhpWord does NOT escape XML special characters (&, <, >) in addText()
        // by default — Settings::$outputEscapingEnabled starts false, so
        // Writer\Word2007\Element\AbstractElement::writeText() calls
        // writeRaw() instead of XMLWriter::text(). Every section below passes
        // through dynamic, DB-sourced strings (chapter names, misconception
        // descriptions, badge names) as well as static titles containing "&",
        // so without this the generated .docx has malformed word/document.xml
        // and Word refuses to open it, even though the surrounding ZIP
        // container is perfectly valid — exactly what happened before this
        // was added.
        \PhpOffice\PhpWord\Settings::setOutputEscapingEnabled(true);

        $phpWord = new PhpWord();
        $phpWord->setDefaultFontName(self::FONT);
        $phpWord->setDefaultFontSize(10);
        $phpWord->getDocumentProperties()
            ->setTitle($title)
            ->setDescription('Generated by the PAL Student Activity & Performance Report.');

        $section = $phpWord->addSection();

        $this->titleBlock($section, (array) ($reportData['scope'] ?? []), $title);
        $this->masteryOverviewSection($section, (array) ($reportData['mastery_overview'] ?? []));
        $this->performanceSection($section, (array) ($reportData['diagnostic_performance'] ?? []), (array) ($reportData['adaptive_performance'] ?? []));
        $this->misconceptionSection($section, (array) ($reportData['misconception_analysis'] ?? []));
        $this->gamificationEngagementSection($section, (array) ($reportData['gamification'] ?? []), (array) ($reportData['engagement'] ?? []));
        if (isset($reportData['intelligence'])) {
            // Student-report only — buildClassReport() never sets this key,
            // so a class .docx silently skips this section rather than
            // rendering an empty/fabricated one.
            $this->intelligenceSection($section, (array) $reportData['intelligence']);
        }
        $this->bulletSection($section, $bulletsHeading, (array) ($reportData[$bulletsKey] ?? []));

        $tmp = tempnam(sys_get_temp_dir(), 'docx');
        IOFactory::createWriter($phpWord, 'Word2007')->save($tmp);
        $binary = (string) file_get_contents($tmp);
        @unlink($tmp);

        return $binary;
    }

    /** Title, generated-at stamp, and a label/value table of whatever scope the report carries. */
    private function titleBlock(Section $section, array $scope, string $title): void
    {
        $section->addText($title, ['bold' => true, 'size' => 20, 'color' => self::INK]);
        $section->addText('Generated ' . now()->toDayDateTimeString(), ['size' => 9, 'color' => self::MUTED]);
        $section->addTextBreak(1);

        $table = $section->addTable(self::TABLE_STYLE);
        foreach (self::SCOPE_LABELS as $key => $label) {
            if (! array_key_exists($key, $scope) || $scope[$key] === null) {
                continue;
            }

            $row = $table->addRow();
            $row->addCell(2600, self::HEADER_CELL)->addText($label, ['bold' => true, 'size' => 9]);
            $row->addCell(6400)->addText((string) $scope[$key], self::BODY_FONT);
        }

        $section->addTextBreak(1);
    }

    /** Mastery overview — the headline counts, then one row per chapter. */
    private function masteryOverviewSection(Section $section, array $overview): void
    {
        $section->addText('Mastery Overview', self::HEADING_FONT, self::HEADING_PARA);

        $avg = isset($overview['mastery_estimate_avg']) && $overview['mastery_estimate_avg'] !== null
            ? number_format((float) $overview['mastery_estimate_avg'], 1) . '%'
            : 'n/a';

        $section->addText(sprintf(
            'Source: %s. %d node(s) total — %d mastered, %d learning, %d unseen, %d misconception-flagged. Average mastery estimate: %s.',
            (string) ($overview['source'] ?? 'learner_node_state'),
            (int) ($overview['nodes_total'] ?? 0),
            (int) ($overview['mastered'] ?? 0),
            (int) ($overview['learning'] ?? 0),
            (int) ($overview['unseen'] ?? 0),
            (int) ($overview['misconception_flagged'] ?? 0),
            $avg
        ), self::BODY_FONT);
        $section->addTextBreak(1);

        $byChapter = (array) ($overview['by_chapter'] ?? []);
        if ($byChapter === []) {
            $section->addText('No chapter-level data is available for this scope.', ['italic' => true, 'size' => 9]);
            $section->addTextBreak(1);

            return;
        }

        $this->addChartImage($section, $this->charts->masteryByChapterChart($byChapter));

        $widths = [2600, 1100, 1100, 1100, 1100, 1100, 1500];
        $table = $section->addTable(self::TABLE_STYLE);
        $row = $table->addRow();
        foreach (['Chapter', 'Nodes', 'Mastered', 'Learning', 'Unseen', 'Flagged', 'Avg. mastery'] as $i => $label) {
            $row->addCell($widths[$i], self::HEADER_CELL)->addText($label, self::HEADER_FONT);
        }

        foreach ($byChapter as $chapter) {
            $row = $table->addRow();
            $row->addCell($widths[0])->addText((string) ($chapter['chapter_name'] ?? 'Unassigned'), self::BODY_FONT);
            $row->addCell($widths[1])->addText((string) ($chapter['nodes_total'] ?? 0), self::BODY_FONT);
            $row->addCell($widths[2])->addText((string) ($chapter['mastered'] ?? 0), self::BODY_FONT);
            $row->addCell($widths[3])->addText((string) ($chapter['learning'] ?? 0), self::BODY_FONT);
            $row->addCell($widths[4])->addText((string) ($chapter['unseen'] ?? 0), self::BODY_FONT);
            $row->addCell($widths[5])->addText((string) ($chapter['misconception_flagged'] ?? 0), self::BODY_FONT);
            $row->addCell($widths[6])->addText(
                isset($chapter['mastery_estimate_avg']) && $chapter['mastery_estimate_avg'] !== null
                    ? number_format((float) $chapter['mastery_estimate_avg'], 1) . '%'
                    : 'n/a',
                self::BODY_FONT
            );
        }

        $section->addTextBreak(1);
    }

    /** Diagnostic + adaptive performance, with a plain-text trend glyph instead of a chart. */
    private function performanceSection(Section $section, array $diagnostic, array $adaptive): void
    {
        $section->addText('Diagnostic & Adaptive Performance', self::HEADING_FONT, self::HEADING_PARA);

        $diagAvg = isset($diagnostic['avg_percentage']) && $diagnostic['avg_percentage'] !== null
            ? number_format((float) $diagnostic['avg_percentage'], 1) . '%'
            : 'n/a';
        $adaptAcc = isset($adaptive['accuracy']) && $adaptive['accuracy'] !== null
            ? number_format((float) $adaptive['accuracy'], 1) . '%'
            : 'n/a';

        $section->addText(sprintf(
            'Diagnostic: %d attempt(s), average %s. Adaptive practice: %d response(s), accuracy %s.',
            (int) ($diagnostic['attempts_count'] ?? 0),
            $diagAvg,
            (int) ($adaptive['responses_count'] ?? 0),
            $adaptAcc
        ), self::BODY_FONT);
        $section->addTextBreak(1);

        $trend = (array) ($diagnostic['trend'] ?? []);
        if ($trend !== []) {
            $section->addText('Diagnostic trend', ['bold' => true, 'size' => 10]);
            $this->addChartImage($section, $this->charts->diagnosticTrendChart($trend));

            $table = $section->addTable(self::TABLE_STYLE);
            $row = $table->addRow();
            foreach (['Date', 'Percentage', 'Trend'] as $label) {
                $row->addCell(3000, self::HEADER_CELL)->addText($label, self::HEADER_FONT);
            }

            $previous = null;
            foreach ($trend as $point) {
                $percentage = (float) ($point['percentage'] ?? 0);
                $row = $table->addRow();
                $row->addCell(3000)->addText((string) ($point['date'] ?? ''), self::BODY_FONT);
                $row->addCell(3000)->addText(number_format($percentage, 1) . '%', self::BODY_FONT);
                $row->addCell(3000)->addText($this->trendGlyph($previous, $percentage), ['size' => 11, 'bold' => true]);
                $previous = $percentage;
            }

            $section->addTextBreak(1);
        }

        $byBand = (array) ($diagnostic['by_difficulty_band'] ?? []);
        if ($byBand !== []) {
            $table = $section->addTable(self::TABLE_STYLE);
            $row = $table->addRow();
            foreach (['Band', 'Served', 'Correct', 'Incorrect', 'Unanswered', 'Percentage'] as $label) {
                $row->addCell(1800, self::HEADER_CELL)->addText($label, self::HEADER_FONT);
            }

            foreach ($byBand as $band => $stats) {
                $row = $table->addRow();
                $row->addCell(1800)->addText(ucfirst((string) $band), self::BODY_FONT);
                $row->addCell(1800)->addText((string) ($stats['served'] ?? 0), self::BODY_FONT);
                $row->addCell(1800)->addText((string) ($stats['correct'] ?? 0), self::BODY_FONT);
                $row->addCell(1800)->addText((string) ($stats['incorrect'] ?? 0), self::BODY_FONT);
                $row->addCell(1800)->addText((string) ($stats['unanswered'] ?? 0), self::BODY_FONT);
                $row->addCell(1800)->addText(
                    isset($stats['percentage']) && $stats['percentage'] !== null ? number_format((float) $stats['percentage'], 1) . '%' : 'n/a',
                    self::BODY_FONT
                );
            }

            $section->addTextBreak(1);
        }

        $ruleBreakdown = (array) ($adaptive['rule_fired_breakdown'] ?? []);
        if ($ruleBreakdown !== []) {
            $section->addText('Adaptive rule-fired breakdown', ['bold' => true, 'size' => 10]);
            $table = $section->addTable(self::TABLE_STYLE);
            $row = $table->addRow();
            foreach (['Rule', 'Count'] as $label) {
                $row->addCell(4500, self::HEADER_CELL)->addText($label, self::HEADER_FONT);
            }

            foreach ($ruleBreakdown as $rule => $count) {
                $row = $table->addRow();
                $row->addCell(4500)->addText((string) $rule, self::BODY_FONT);
                $row->addCell(4500)->addText((string) $count, self::BODY_FONT);
            }

            $section->addTextBreak(1);
        }
    }

    /**
     * Embeds a chart PNG (StudentActivityChartRenderer's return shape) at a
     * fixed display width, scaling height to match its true pixel aspect
     * ratio so it never stretches. `addImage()` takes the binary directly —
     * see StudentActivityChartRenderer's own docblock for why no temp file
     * is needed here, the same reasoning as this service's own tempnam/save/
     * unlink round-trip for the finished .docx, just one layer in.
     */
    private function addChartImage(Section $section, ?array $chart): void
    {
        if ($chart === null) {
            return;
        }

        $displayWidth = 460;
        $displayHeight = (int) round($displayWidth * ($chart['height'] / $chart['width']));

        $section->addImage($chart['binary'], [
            'width' => $displayWidth,
            'height' => $displayHeight,
        ]);
        $section->addTextBreak(1);
    }

    /** ▲ improved / ▼ declined / ▬ first point or unchanged. */
    private function trendGlyph(?float $previous, float $current): string
    {
        if ($previous === null || $current === $previous) {
            return '▬';
        }

        return $current > $previous ? '▲' : '▼';
    }

    private function misconceptionSection(Section $section, array $misconception): void
    {
        $section->addText('Misconception Analysis', self::HEADING_FONT, self::HEADING_PARA);
        $section->addText(sprintf('%d active misconception flag(s) in this scope.', (int) ($misconception['active_count'] ?? 0)), self::BODY_FONT);
        $section->addTextBreak(1);

        $top = (array) ($misconception['top_misconceptions'] ?? []);
        if ($top === []) {
            $section->addText('No misconceptions are currently flagged.', ['italic' => true, 'size' => 9]);
            $section->addTextBreak(1);

            return;
        }

        $table = $section->addTable(self::TABLE_STYLE);
        $row = $table->addRow();
        foreach (['Tag', 'Description', 'Corrective action', 'Flags'] as $label) {
            $row->addCell(2250, self::HEADER_CELL)->addText($label, self::HEADER_FONT);
        }

        foreach ($top as $item) {
            $row = $table->addRow();
            $row->addCell(2250)->addText((string) ($item['tag'] ?? ''), self::BODY_FONT);
            $row->addCell(2250)->addText((string) ($item['description'] ?? ''), self::BODY_FONT);
            $row->addCell(2250)->addText((string) ($item['corrective_action'] ?? ''), self::BODY_FONT);
            $row->addCell(2250)->addText((string) ($item['detection_count'] ?? 0), self::BODY_FONT);
        }

        $section->addTextBreak(1);
    }

    /**
     * Gamification (shape differs between a student's streak+badges and a
     * class's "N of M students have data"), then engagement — always the
     * explicit insufficient-data sentence (see the class docblock).
     */
    private function gamificationEngagementSection(Section $section, array $gamification, array $engagement): void
    {
        $section->addText('Gamification & Engagement', self::HEADING_FONT, self::HEADING_PARA);

        $hasData = (bool) ($gamification['has_sufficient_data'] ?? false);

        if (array_key_exists('streak', $gamification)) {
            // Student shape.
            if (! $hasData) {
                $section->addText('Not enough streak/badge activity has been recorded yet for this learner.', ['italic' => true, 'size' => 9]);
            } else {
                $streak = $gamification['streak'];
                if ($streak !== null) {
                    $section->addText(sprintf(
                        'Current streak: %d day(s). Longest streak: %d day(s). Total active days: %d.',
                        (int) ($streak['current_streak'] ?? 0),
                        (int) ($streak['longest_streak'] ?? 0),
                        (int) ($streak['total_active_days'] ?? 0)
                    ), self::BODY_FONT);
                }

                $badges = (array) ($gamification['badges'] ?? []);
                if ($badges !== []) {
                    $section->addTextBreak(1);
                    $table = $section->addTable(self::TABLE_STYLE);
                    $row = $table->addRow();
                    foreach (['Badge', 'Category', 'Awarded'] as $label) {
                        $row->addCell(3000, self::HEADER_CELL)->addText($label, self::HEADER_FONT);
                    }

                    foreach ($badges as $badge) {
                        $row = $table->addRow();
                        $row->addCell(3000)->addText((string) ($badge['name'] ?? ''), self::BODY_FONT);
                        $row->addCell(3000)->addText((string) ($badge['category'] ?? ''), self::BODY_FONT);
                        $row->addCell(3000)->addText((string) ($badge['awarded_at'] ?? ''), self::BODY_FONT);
                    }
                }
            }
        } else {
            // Class shape: students_with_data / students_total / message.
            $section->addText((string) ($gamification['message'] ?? ''), self::BODY_FONT);
        }

        $section->addTextBreak(1);

        $section->addText('Engagement', ['bold' => true, 'size' => 10]);
        $section->addText(
            (string) ($engagement['message'] ?? 'Not enough session/activity data has been recorded yet for meaningful engagement metrics.'),
            ['italic' => true, 'size' => 9]
        );
        $section->addTextBreak(1);
    }

    /** Risk-kind key (StudentActivityReportService's `risk` map) -> display label. */
    private const RISK_LABELS = [
        'disengagement' => 'Disengagement',
        'failure' => 'Failure',
        'burnout' => 'Burnout',
    ];

    /**
     * Learning Intelligence — velocity/plateau/regression, three risk kinds,
     * and remediation for the top active misconception. Student report only
     * (see render()'s isset() guard); every figure here comes straight from
     * StudentActivityReportService::buildIntelligence(), already shaped with
     * has_data flags, so this method's only job is to render those flags
     * honestly — never a fabricated 0%/blank score where has_data is false.
     */
    private function intelligenceSection(Section $section, array $intelligence): void
    {
        $section->addText('Learning Intelligence', self::HEADING_FONT, self::HEADING_PARA);

        $stalenessNote = (string) ($intelligence['staleness_note'] ?? '');
        if ($stalenessNote !== '') {
            $section->addText($stalenessNote, ['italic' => true, 'size' => 9, 'color' => self::MUTED]);
            $section->addTextBreak(1);
        }

        $this->intelligenceSummaryTable($section, $intelligence);
        $this->intelligenceRiskTable($section, (array) ($intelligence['risk'] ?? []));
        $this->intelligenceRemediationParagraph($section, $intelligence['remediation'] ?? null);
    }

    /** Velocity / plateau / regression, one row each. */
    private function intelligenceSummaryTable(Section $section, array $intelligence): void
    {
        $widths = [2600, 2600, 4800];
        $table = $section->addTable(self::TABLE_STYLE);
        $row = $table->addRow();
        foreach (['Metric', 'As of', 'Status'] as $i => $label) {
            $row->addCell($widths[$i], self::HEADER_CELL)->addText($label, self::HEADER_FONT);
        }

        $velocity = (array) ($intelligence['velocity'] ?? []);
        $row = $table->addRow();
        $row->addCell($widths[0])->addText('Velocity (weekly)', self::BODY_FONT);
        $row->addCell($widths[1])->addText($this->intelligenceAsOf($velocity['as_of'] ?? null), self::BODY_FONT);
        $row->addCell($widths[2])->addText($this->velocityStatusText($velocity), self::BODY_FONT);

        $plateau = (array) ($intelligence['plateau'] ?? []);
        $row = $table->addRow();
        $row->addCell($widths[0])->addText('Plateau', self::BODY_FONT);
        $row->addCell($widths[1])->addText($this->intelligenceAsOf($plateau['as_of'] ?? null), self::BODY_FONT);
        $row->addCell($widths[2])->addText($this->plateauStatusText($plateau), self::BODY_FONT);

        $regression = (array) ($intelligence['regression'] ?? []);
        $row = $table->addRow();
        $row->addCell($widths[0])->addText('Regression', self::BODY_FONT);
        $row->addCell($widths[1])->addText($this->intelligenceAsOf($regression['as_of'] ?? null), self::BODY_FONT);
        $row->addCell($widths[2])->addText($this->regressionStatusText($regression), self::BODY_FONT);

        $section->addTextBreak(1);
    }

    /** ISO8601 'as_of' -> plain date, or 'n/a' when the engine had no evidence to anchor to. */
    private function intelligenceAsOf(?string $asOf): string
    {
        return ($asOf === null || $asOf === '') ? 'n/a' : substr($asOf, 0, 10);
    }

    private function velocityStatusText(array $velocity): string
    {
        if (! (bool) ($velocity['has_data'] ?? false)) {
            return 'Not enough data yet';
        }

        $classification = ucfirst((string) ($velocity['classification'] ?? 'unknown'));
        $value = isset($velocity['velocity']) ? number_format((float) $velocity['velocity'], 2) : 'n/a';

        return sprintf('%s — %s concepts/day', $classification, $value);
    }

    private function plateauStatusText(array $plateau): string
    {
        if (! (bool) ($plateau['has_data'] ?? false)) {
            return 'Not enough data yet';
        }

        if (! (bool) ($plateau['is_plateau'] ?? false)) {
            return 'No plateau detected';
        }

        return sprintf('Plateau for %d day(s)', (int) ($plateau['days_in_plateau'] ?? 0));
    }

    private function regressionStatusText(array $regression): string
    {
        if (! (bool) ($regression['has_data'] ?? false)) {
            return 'Not enough data yet';
        }

        if (! (bool) ($regression['is_regressing'] ?? false)) {
            return 'No regression detected';
        }

        $decline = isset($regression['decline_percent']) && $regression['decline_percent'] !== null
            ? number_format((float) $regression['decline_percent'], 1) . '%'
            : 'n/a';

        return sprintf('Regressing — %s decline', $decline);
    }

    /** Disengagement / failure / burnout, one row each. */
    private function intelligenceRiskTable(Section $section, array $risk): void
    {
        $section->addText('Risk flags', ['bold' => true, 'size' => 10]);

        $widths = [2500, 1800, 1800, 3900];
        $table = $section->addTable(self::TABLE_STYLE);
        $row = $table->addRow();
        foreach (['Risk kind', 'Score', 'Level', 'Top signal'] as $i => $label) {
            $row->addCell($widths[$i], self::HEADER_CELL)->addText($label, self::HEADER_FONT);
        }

        foreach (self::RISK_LABELS as $key => $label) {
            $kind = (array) ($risk[$key] ?? []);
            $hasData = (bool) ($kind['has_data'] ?? false);

            $row = $table->addRow();
            $row->addCell($widths[0])->addText($label, self::BODY_FONT);

            if (! $hasData) {
                // Never a fabricated 0%/blank score — "no session data" is a
                // different fact from "measured zero risk".
                $row->addCell($widths[1])->addText('n/a', self::BODY_FONT);
                $row->addCell($widths[2])->addText('Not enough session data yet', ['italic' => true, 'size' => 9]);
                $row->addCell($widths[3])->addText('n/a', self::BODY_FONT);

                continue;
            }

            $score = isset($kind['risk_score']) && $kind['risk_score'] !== null
                ? number_format((float) $kind['risk_score'] * 100, 1) . '%'
                : 'n/a';
            $level = isset($kind['risk_level']) ? ucfirst((string) $kind['risk_level']) : 'n/a';

            $row->addCell($widths[1])->addText($score, self::BODY_FONT);
            $row->addCell($widths[2])->addText($level, self::BODY_FONT);
            $row->addCell($widths[3])->addText($this->intelligenceTopSignal((array) ($kind['signals'] ?? [])), self::BODY_FONT);
        }

        $section->addTextBreak(1);
    }

    /** The highest-weighted raw signal driving one risk score, e.g. "Frustration (0.80)". */
    private function intelligenceTopSignal(array $signals): string
    {
        $topKey = null;
        $topValue = -1.0;

        foreach ($signals as $key => $value) {
            $value = (float) $value;
            if ($value > $topValue) {
                $topValue = $value;
                $topKey = $key;
            }
        }

        if ($topKey === null) {
            return 'n/a';
        }

        return sprintf('%s (%s)', ucfirst(str_replace('_', ' ', (string) $topKey)), number_format($topValue, 2));
    }

    /**
     * Top misconception's tag + excerpt, or an honest "nothing to
     * remediate". `$remediation` is already the lean {tag, content_excerpt}
     * shape StudentActivityReportService::simplifyRemediation() produces —
     * the same shape the JSON API returns — not the intelligence engine's
     * raw nested output, so there's nothing left to extract here.
     */
    private function intelligenceRemediationParagraph(Section $section, ?array $remediation): void
    {
        $section->addText('Remediation', ['bold' => true, 'size' => 10]);

        $tag = (string) ($remediation['tag'] ?? '');
        if ($tag === '') {
            $section->addText('No active misconception to remediate.', ['italic' => true, 'size' => 9]);
            $section->addTextBreak(1);

            return;
        }

        $excerpt = (string) ($remediation['content_excerpt'] ?? '');

        $section->addText(sprintf(
            '%s: %s',
            $tag,
            $excerpt !== '' ? $excerpt : 'No remediation content recorded yet for this misconception.'
        ), self::BODY_FONT);
        $section->addTextBreak(1);
    }

    /** Recommendations (student) or action items (class) as a bullet list. */
    private function bulletSection(Section $section, string $heading, array $items): void
    {
        $section->addText($heading, self::HEADING_FONT, self::HEADING_PARA);

        if ($items === []) {
            $section->addText('Nothing to report for this scope.', ['italic' => true, 'size' => 9]);

            return;
        }

        foreach ($items as $item) {
            $section->addListItem((string) $item, 0, self::BODY_FONT);
        }
    }
