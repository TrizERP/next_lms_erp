        <h4>KNOWING CHILDREN BETTER</h4>
        <h5>Challenging Behaviours to Identify</h5>
        <ul>
            <li>The child causes harm or risk to self or others.</li>
            <li>The behaviour interferes with learning and relationships.</li>
            <li>The child is extremely shy, withdrawn, or passive.</li>
            <li>There is developmental delay or inappropriate age-related behaviour.</li>
        </ul>

        <h5>Improving Parent-Child Relationship</h5>
        <ul>
            <li>Show love, greet them with a smile, and encourage honest interaction.</li>
            <li>Listen and empathise with your child's feelings.</li>
            <li>Be available and free from distractions.</li>
            <li>Spend quality time together.</li>
            <li>Listen to the whole story before forming conclusions.</li>
            <li>Know your child's friends.</li>
        </ul>
