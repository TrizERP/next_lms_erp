        <h4>COUNSELLING - A PROGRAM WITH A DIFFERENCE</h4>
        <p>Counselling is a process where a trained professional provides support and guidance to individuals or groups facing challenges, difficulties, or seeking personal development. It involves confidential conversations to explore emotions, thoughts, and behaviours, aiming to help the person gain insights and make positive changes in life.</p>
        
        <p>The National Education Policy (NEP) 2020 recognises that mental health is integral to education, focusing on socio-emotional aspects of development.</p>
        
        <p>As per CBSE bye-law 2.4.12, our school has full-time counsellors and wellness teachers. CBSE also provides psychological counselling to Class X and XII examinees and differently-abled students.</p>
        
        <p>A presentation titled "Knowing Your Child Better" is available on the CBSE website:<br>
        <a href="https://www.cbse.gov.in/cbsenew/prunit_temp/index.html">https://www.cbse.gov.in/cbsenew/prunit_temp/index.html</a></p>
